#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const FUNCTION_NULLABILITY = Object.freeze([
  Object.freeze({
    name: "accept_invitation_atomic",
    nextName: "bump_session_epoch",
    fields: Object.freeze([
      "invitation_id",
      "organization_id",
      "organization_name",
      "organization_slug",
    ]),
  }),
  Object.freeze({
    name: "consume_password_reset",
    nextName: "expire_stale_invitations",
    fields: Object.freeze(["auth_user_id", "user_id"]),
  }),
  Object.freeze({
    name: "claim_mfa_recovery",
    nextName: "clear_login_attempts",
    fields: Object.freeze(["auth_user_id", "operation_id", "status"]),
  }),
]);
const API_HEADER =
  "/* eslint-disable */\n" +
  "// GENERATED by `pnpm --filter infrastructure run db:types`. Do not edit.\n";

/**
 * Supabase cannot represent nullability for individual columns returned by a
 * PostgreSQL `returns table` function. Tighten the generated contract for the
 * known nullable result columns and fail if the generator changes its shape.
 */
export function normalizeDatabaseTypes(source) {
  return (
    FUNCTION_NULLABILITY.reduce(
      normalizeFunctionNullability,
      source,
    ).trimEnd() + "\n"
  );
}

function normalizeFunctionNullability(source, specification) {
  const startMarker = `      ${specification.name}: {`;
  const endMarker = `      ${specification.nextName}:`;
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start);

  if (start === -1 || end === -1 || end <= start) {
    throw new Error(
      `Generated types are missing the ${specification.name} function block`,
    );
  }

  const prefix = source.slice(0, start);
  let functionBlock = source.slice(start, end);
  const suffix = source.slice(end);

  for (const field of specification.fields) {
    const fieldPattern = new RegExp(
      `^          ${field}: string(?: \\| null)?$`,
      "gm",
    );
    const matches = functionBlock.match(fieldPattern) ?? [];

    if (matches.length !== 1) {
      throw new Error(
        `Expected exactly one ${field} field in ${specification.name}`,
      );
    }

    functionBlock = functionBlock.replace(
      fieldPattern,
      `          ${field}: string | null`,
    );
  }

  return `${prefix}${functionBlock}${suffix}`;
}

async function main() {
  const [sourcePath, apiTargetPath] = process.argv.slice(2);
  if (!sourcePath || !apiTargetPath) {
    throw new Error(
      "Usage: normalize-database-types.mjs <source> <api-target>",
    );
  }

  const normalized = normalizeDatabaseTypes(await readFile(sourcePath, "utf8"));
  await Promise.all([
    writeFile(sourcePath, normalized),
    writeFile(apiTargetPath, `${API_HEADER}${normalized}`),
  ]);
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await main();
}
